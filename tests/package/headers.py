#!/usr/bin/env python3
"""Writes headers.cpp: one section per installed C++ header, so each compiles on its own.

Usage:
    python3 tests/package/headers.py [--check]

The headers are those cmake/AffrescoUIInstall.cmake installs: modules/<module>/include/affresco/**/*.hpp for every
module but the C API's. CMakeLists.txt here builds headers.cpp once per section, with AFFRESCOUI_HEADER set to its
index, against the installed package. --check exits with 1 when headers.cpp is not up to date, writing nothing. Only
the Python standard library is needed.
"""

import argparse
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUTPUT = os.path.join(HERE, "headers.cpp")
MODULES = ["core", "data", "render", "format", "vcs", "channel", "net", "services", "automation", "screen"]


def headers():
    """The installed headers' include names, sorted: affresco/Screen.hpp, affresco/core/Json.hpp, ..."""
    names = []
    for module in MODULES:
        include = os.path.join(ROOT, "modules", module, "include")
        for path in glob.glob(os.path.join(include, "affresco", "**", "*.hpp"), recursive=True):
            names.append(os.path.relpath(path, include).replace(os.sep, "/"))
    return sorted(names)


def text(names):
    """headers.cpp for these headers."""
    lines = [
        "/// @file",
        "/// @brief Each public header on its own: built once per section with AFFRESCOUI_HEADER set to its index, so a",
        "/// header that needs another it doesn't include fails here. Generated by headers.py: don't edit it.",
        "",
        f"// headers: {len(names)}",
        "",
    ]
    for index, name in enumerate(names):
        lines.append(f"#{'if' if index == 0 else 'elif'} AFFRESCOUI_HEADER == {index}")
        lines.append(f"#include <{name}>")
    lines += ["#else", '#error "AFFRESCOUI_HEADER names no header"', "#endif", ""]
    return "\n".join(lines)


def main():
    """Writes headers.cpp, or with --check says whether it is up to date."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit with 1 when headers.cpp is not up to date")
    options = parser.parse_args()
    wanted = text(headers())
    current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
    if options.check:
        if current != wanted:
            sys.exit("headers.cpp is not up to date: run python3 tests/package/headers.py")
        return
    if current != wanted:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
            out.write(wanted)


if __name__ == "__main__":
    main()
